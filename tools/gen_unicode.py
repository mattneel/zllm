"""Generate src/tokenizer/unicode_data.zig from Python's unicodedata.

    python3 tools/gen_unicode.py | zig fmt --stdin > src/tokenizer/unicode_data.zig

Tables: general-category ranges for L, M and N; White_Space; and the NFC data
(canonical decompositions, canonical combining classes, primary composites).
The Unicode version is pinned below; regenerate only with a matching Python.
"""

from __future__ import annotations

import sys
import unicodedata

UNICODE_VERSION = "16.0.0"
MAX_CP = 0x110000

# PropList.txt White_Space; unicodedata has no property API.
WHITE_SPACE = [
    (0x0009, 0x000D),
    (0x0020, 0x0020),
    (0x0085, 0x0085),
    (0x00A0, 0x00A0),
    (0x1680, 0x1680),
    (0x2000, 0x200A),
    (0x2028, 0x2029),
    (0x202F, 0x202F),
    (0x205F, 0x205F),
    (0x3000, 0x3000),
]

# Hangul syllables compose algorithmically; tables exclude them.
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX_CP):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def category_prefix(prefix: str):
    return lambda cp: unicodedata.category(chr(cp)).startswith(prefix)


def canonical_decompositions() -> list[tuple[int, list[int]]]:
    out = []
    for cp in range(MAX_CP):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        d = unicodedata.decomposition(chr(cp))
        if d and not d.startswith("<"):
            out.append((cp, [int(x, 16) for x in d.split()]))
    return out


def combining_classes() -> list[tuple[int, int, int]]:
    """Runs of equal nonzero canonical combining class: (first, last, ccc)."""
    out: list[tuple[int, int, int]] = []
    for cp in range(MAX_CP):
        ccc = unicodedata.combining(chr(cp))
        if ccc == 0:
            continue
        if out and out[-1][1] == cp - 1 and out[-1][2] == ccc:
            out[-1] = (out[-1][0], cp, ccc)
        else:
            out.append((cp, cp, ccc))
    return out


def primary_composites(decomps) -> list[tuple[int, int, int]]:
    """(first, second, composite) for pairs NFC recomposes; excludes exclusions and singletons."""
    out = []
    for cp, parts in decomps:
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            out.append((parts[0], parts[1], cp))
    out.sort()
    return out


def emit_ranges(w, name: str, rs) -> None:
    w(f"pub const {name} = [_]Range{{\n")
    for a, b in rs:
        w(f"    .{{ .first = 0x{a:X}, .last = 0x{b:X} }},\n")
    w("};\n\n")


def main() -> None:
    if unicodedata.unidata_version != UNICODE_VERSION:
        sys.exit(f"need Unicode {UNICODE_VERSION}, this Python has {unicodedata.unidata_version}")

    decomps = canonical_decompositions()
    composites = primary_composites(decomps)
    decomposable = {cp for cp, _ in decomps}
    seconds = {b for _, b, _ in composites}
    hangul_vt = set(range(0x1161, 0x1176)) | set(range(0x11A8, 0x11C3))

    def nfc_unsafe(cp: int) -> bool:
        return cp in decomposable or cp in seconds or cp in hangul_vt or unicodedata.combining(chr(cp)) != 0

    out: list[str] = []
    w = out.append
    w("//! Generated by tools/gen_unicode.py. Do not edit.\n")
    w(f"//! Unicode {UNICODE_VERSION}.\n\n")
    w(f'pub const version = "{UNICODE_VERSION}";\n\n')
    w("pub const Range = struct { first: u21, last: u21 };\n")
    w("pub const ClassRange = struct { first: u21, last: u21, ccc: u8 };\n")
    w("pub const Decomposition = struct { cp: u21, start: u16, len: u8 };\n")
    w("pub const Composition = struct { first: u21, second: u21, composite: u21 };\n\n")

    emit_ranges(w, "letter", ranges(category_prefix("L")))
    emit_ranges(w, "mark", ranges(category_prefix("M")))
    emit_ranges(w, "number", ranges(category_prefix("N")))
    emit_ranges(w, "white_space", WHITE_SPACE)
    w("/// Code points that may change under NFC, alone or with a neighbour: canonically\n")
    w("/// decomposable, non-starters, and second halves of compositions. Text without\n")
    w("/// any of them is already NFC.\n")
    emit_ranges(w, "nfc_unsafe", ranges(nfc_unsafe))

    w("pub const combining_class = [_]ClassRange{\n")
    for a, b, c in combining_classes():
        w(f"    .{{ .first = 0x{a:X}, .last = 0x{b:X}, .ccc = {c} }},\n")
    w("};\n\n")

    flat: list[int] = []
    w("/// Single-level canonical decompositions, sorted by code point; apply recursively.\n")
    w("pub const decomposition = [_]Decomposition{\n")
    for cp, parts in decomps:
        w(f"    .{{ .cp = 0x{cp:X}, .start = {len(flat)}, .len = {len(parts)} }},\n")
        flat.extend(parts)
    w("};\n\n")
    w("pub const decomposition_data = [_]u21{\n")
    for i in range(0, len(flat), 8):
        w("    " + " ".join(f"0x{x:X}," for x in flat[i : i + 8]) + "\n")
    w("};\n\n")

    w("/// Primary composites sorted by (first, second).\n")
    w("pub const composition = [_]Composition{\n")
    for a, b, c in composites:
        w(f"    .{{ .first = 0x{a:X}, .second = 0x{b:X}, .composite = 0x{c:X} }},\n")
    w("};\n")

    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
